// Dev-time generator: produces packages/zedpdf/src/font/standard14-data.ts
// Source metrics: Adobe Core14 AFM data as packaged by @pdf-lib/standard-fonts (MIT).
// Usage: node scripts/gen-standard-fonts.cjs <path-to-node_modules>
const path = require('path');
const fs = require('fs');
const nm = process.argv[2];
const { Font, Encodings } = require(path.join(nm, '@pdf-lib/standard-fonts'));
const cp1252 = new TextDecoder('windows-1252');
const fonts = ['Helvetica', 'Helvetica-Bold', 'Times-Roman', 'Times-Bold', 'Times-Italic', 'Times-BoldItalic'];
let out = '// GENERATED by scripts/gen-standard-fonts.cjs from Adobe Core14 AFM metrics\n// (via @pdf-lib/standard-fonts, MIT). Widths in 1/1000 em for WinAnsi codes 32..255.\n';
out += 'export const STD_WIDTHS: Record<string, number[]> = {\n';
const metrics = {};
for (const name of fonts) {
  const f = Font.load(name);
  const w = [];
  for (let code = 32; code <= 255; code++) {
    const ch = cp1252.decode(new Uint8Array([code]));
    const cp = ch.codePointAt(0);
    let width = 0;
    try {
      const enc = Encodings.WinAnsi.encodeUnicodeCodePoint(cp);
      width = f.getWidthOfGlyph(enc.name) || 0;
    } catch { width = 0; }
    w.push(width);
  }
  out += `  '${name}': [${w.join(',')}],\n`;
  metrics[name] = { ascender: f.Ascender, descender: f.Descender, capHeight: f.CapHeight, underlinePosition: f.UnderlinePosition, underlineThickness: f.UnderlineThickness };
}
out += '};\n';
out += `export const STD_METRICS: Record<string, { ascender: number; descender: number; capHeight: number; underlinePosition: number; underlineThickness: number }> = ${JSON.stringify(metrics, null, 2)};\n`;
fs.writeFileSync(path.join(__dirname, '../packages/zedpdf/src/font/standard14-data.ts'), out);
console.log('ok');
